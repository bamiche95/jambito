/**
 * Syllabus data layer for every exam board the site publishes.
 *
 * `data/syllabus/` holds the official JAMB (UTME) outlines and
 * `data/syllabus/waec/` the WAEC (WASSCE) ones — one JSON file per subject. They
 * are imported statically (not read with `fs`) so the whole syllabus ships inside
 * the server bundle and every `/syllabus/**` route can be prerendered at build
 * time. Adding a board means adding its files plus one entry in `RAW_SOURCES`;
 * the `/syllabus/<exam>` routes and the sitemap then pick it up automatically.
 *
 * The source files are *not* perfectly uniform, so everything is funnelled
 * through `normalizeSyllabus()` which produces one predictable model:
 *
 *  1. Paired subjects describe each item as
 *     `subtopics: [{ content, objective }]` → content and objective line up 1:1.
 *  2. Split subjects (JAMB Physics, PHE, Music, Principles of Accounting)
 *     describe `subtopics: string[]` plus a separate `objectives: string[]`.
 *
 * Traps worth remembering:
 *  - `topic.id` restarts inside every section (JAMB Commerce has 60 duplicate
 *    ids), so ids are never used as React keys or anchors. Slugs + positions are.
 *  - Subject `"Yorùbá"` contains diacritics; `syllabusSlug()` folds them so the
 *    URL stays clean (`/syllabus/jamb/yoruba`).
 *  - JAMB and WAEC share subject slugs (`biology`, `physics`, …), so exam and
 *    subject slugs are always looked up as a pair — never by subject slug alone.
 *  - The WAEC drop labels its subjects `"WAEC/JAMB"`; `scripts/import-waec-syllabus.mjs`
 *    rewrites that to `"WAEC"` so `/syllabus/[exam]` stays a single segment.
 */
