/**
 * Exam-aware category lookup: the board's own map first, then the shared slug
 * map (`Basketry` has no shared entry, `Physics` does), then a safe default.
 */
function resolveCategory(examSlug: string, subjectSlug: string): SyllabusCategory {
  if (examSlug === "waec") {
    return (
      CATEGORY_BY_WAEC_SUBJECT_SLUG[subjectSlug] ??
      CATEGORY_BY_SUBJECT_SLUG[subjectSlug] ??
      "Sciences"
    );
  }
  return CATEGORY_BY_SUBJECT_SLUG[subjectSlug] ?? "Sciences";
}

