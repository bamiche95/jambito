/** Raw shapes coming out of the JSON files (everything optional/defensive). */
interface RawSyllabus {
  subject?: string;
  exam?: string;
  generalObjectives?: string[];
  recommendedTexts?: string[];
  sections?: RawSection[];
}

interface RawSection {
  sectionTitle?: string;
  topics?: RawTopic[];
}

interface RawTopic {
  id?: number | string;
  title?: string;
  subtopics?: unknown[];
  objectives?: string[];
}

interface RawSubtopic {
  content?: string;
  objective?: string;
}

