/**
 * Slugifies a syllabus title. Same idea as `slugify()` in `lib/catalog.ts` but
 * with Unicode folding so `Yorùbá` → `yoruba` instead of `yor-b`.
 */
export function syllabusSlug(value: string): string {
  return String(value ?? "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase()
    .trim()
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}

/** Normalises any exam segment (`JAMB`, `jamb`) to its canonical slug. */
export function normalizeExamSlug(value: string): string {
  return examNameToSlug(examSlugToName(value));
}

/**
 * Artefacts of the WAEC drop (`[cite: 251, 252]`). `scripts/import-waec-syllabus.mjs`
 * already strips them from `data/syllabus/waec/`; cleaning here as well means a
 * future re-drop that skips the script can never leak them into the UI.
 */
const CITE_MARKER = /\s*\[cite:[^\]]*\]/g;

function cleanText(value: unknown): string {
  return typeof value === "string" ? value.replace(CITE_MARKER, "").trim() : "";
}

function cleanList(values: unknown): string[] {
  if (!Array.isArray(values)) return [];
  return values.map(cleanText).filter(Boolean);
}

/** Appends `-2`, `-3`, … when two titles slugify to the same value. */
function claimSlug(base: string, used: Set<string>, fallback: string): string {
  const root = base || fallback;
  let slug = root;
  let suffix = 2;
  while (used.has(slug)) {
    slug = `${root}-${suffix}`;
    suffix += 1;
  }
  used.add(slug);
  return slug;
}

